// Bundles packages/agent-host (TS ESM) into a single CJS file that the Electron
// main process can require() directly. Zod is inlined, so the packaged app has
// no extra runtime dependency.
//
// Usage: node build-agent-host.mjs   (writes agent-host.bundle.cjs)
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import fs from 'node:fs';

// esbuild lives in the pnpm virtual store (a transitive dep of vite/vitest), not
// in any direct dependency chain we control. Resolve the newest store copy so
// the desktop package needs no extra install.
const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.join(here, '..', '..');
const storeDir = path.join(repoRoot, 'node_modules', '.pnpm');
const esbuildDirs = fs.existsSync(storeDir)
  ? fs.readdirSync(storeDir).filter((d) => /^esbuild@\d/.test(d)).sort()
  : [];
if (esbuildDirs.length === 0) {
  throw new Error('esbuild not found in pnpm store (node_modules/.pnpm) — run pnpm install first');
}
const esbuildDir = esbuildDirs[esbuildDirs.length - 1];
const { build } = createRequire(
  path.join(storeDir, esbuildDir, 'node_modules', 'esbuild', 'package.json'),
)('esbuild');

await build({
  entryPoints: [path.join(here, '..', '..', 'packages', 'agent-host', 'src', 'index.ts')],
  outfile: path.join(here, 'agent-host.bundle.cjs'),
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node20',
  sourcemap: 'inline',
  logLevel: 'info',
  banner: {
    js: '/* generated by build-agent-host.mjs — do not edit by hand */',
  },
});

console.log('[build-agent-host] wrote agent-host.bundle.cjs');
